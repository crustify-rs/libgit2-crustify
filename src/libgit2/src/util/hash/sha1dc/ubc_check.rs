/// The records of [`SHA1_DVS`]: the 32 disturbance vectors and the record that ends them.
const DV_COUNT: usize = 33;

/// A record of [`SHA1_DVS`], as [`DvInfo::new`] builds it; one it refuses fails the build.
const fn dv(
    dv_type: i32,
    k: i32,
    b: i32,
    recompression_step: i32,
    mask_word: i32,
    mask_bit: i32,
    message_difference: &[u32; STEPS],
) -> DvInfo {
    match DvInfo::new(
        dv_type,
        k,
        b,
        recompression_step,
        mask_word,
        mask_bit,
        *message_difference,
    ) {
        Some(record) => record,
        None => panic!("a record of sha1_dvs is out of the range sha1.c reads"),
    }
}

